import { extractAnswerLabel } from "./text-matching.js";
import type { DumpedConfirmedFact, MisroutedCompanyFact } from "./types.js";

export function createMisroutedCompanyFactsRetryNotice(
  misrouted: MisroutedCompanyFact[]
) {
  const lines = misrouted.map((item) =>
    `- «${extractAnswerLabel(item.fact)}» — подтверждено для места «${item.company}» (sourceIndex ${item.sourceIndex}), но в adaptedBullets этого места не отражено`
  ).join("\n");
  return `
ОШИБКА ПРИВЯЗКИ ПОДТВЕРЖДЁННЫХ ФАКТОВ К ОПЫТУ: кандидат подтвердил следующие факты для
КОНКРЕТНЫХ мест работы, но твой предыдущий ответ не отразил их в опыте этих мест:
${lines}

Верни ИСПРАВЛЕННЫЙ полный JSON той же схемы, в котором каждый из этих фактов встроен в
adaptedBullets именно того места работы, для которого кандидат его подтвердил: сформулируй как
выполненное ДЕЙСТВИЕ в контексте задач этого места, стилистически и по объёму НЕОТЛИЧИМОЕ от
соседних пунктов (разверни ответ кандидата контекстом, уже описанным в этом месте, без новых
цифр), — не как короткую констатацию навыка. Из summary и additionalInfo эти факты убери, если
они там оказались. Остальные части JSON, которые уже были правильными, оставь как в предыдущем
ответе.
`.trim();
}

export function createConfirmedFactsPlacementRetryNotice(
  dumped: DumpedConfirmedFact[]
) {
  const lines = dumped.map((item) => `- [${item.location}] "${item.text}"`).join("\n");
  return `
ОШИБКА РАЗМЕЩЕНИЯ ПОДТВЕРЖДЁННЫХ ФАКТОВ: следующие строки твоего предыдущего ответа — это
почти дословно скопированные ответы кандидата на уточняющие вопросы, а не переписанный текст
резюме:
${lines}

Так делать нельзя: additionalInfo и summary — не место для списка ответов кандидата, даже по
одному пункту на факт. Верни ИСПРАВЛЕННЫЙ полный JSON той же схемы, в котором каждый из этих
фактов встроен по правилу из блока ПОДТВЕРЖДЁННЫЕ КАНДИДАТОМ ФАКТЫ (bullets места работы,
skills с уровнем владения, либо, если факт общий и не привязан ни к одному месту, максимум ОДНО
переформулированное предложение внутри summary) — переписано своими словами, как это сделал бы
карьерный консультант, а не скопировано из ответа. Ни один из этих фактов не должен остаться
отдельной строкой в additionalInfo. Остальные части JSON, которые уже были правильными (опыт,
навыки, не связанные с этими фактами), оставь как в предыдущем ответе.
`.trim();
}
