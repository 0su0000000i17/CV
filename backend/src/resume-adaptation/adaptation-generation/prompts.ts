function formatSetting(value: boolean) {
  return value ? "включено" : "выключено";
}

function createSettingsPrompt(settings: AdaptationSettings) {
  return `
НАСТРОЙКИ АДАПТАЦИИ:
- Сохранить стиль автора: ${formatSetting(settings.preserveAuthorStyle)}
- Усилить достижения: ${formatSetting(settings.strengthenAchievements)}
- Оптимизировать под ATS: ${formatSetting(settings.optimizeForAts)}
- Подстроить навыки под вакансию: ${formatSetting(settings.tailorSkillsToVacancy)}
- Сделать текст более конкретным: ${formatSetting(settings.makeTextMoreSpecific)}
`.trim();
}

type SourceResumeForCounts = {
  experience?: {
    items?: Array<{
      sourceIndex?: number;
      blocks?: Array<{ type?: string; text?: string | null }>;
    }>;
  };
};

function requiredMinBullets(sourceCount: number) {
  if (sourceCount <= 0) return 0;
  if (sourceCount <= 5) return sourceCount;
  return Math.min(sourceCount, 10);
}

function createBulletCountPrompt(resumeMarkdown: string) {
  try {
    const parsed = JSON.parse(resumeMarkdown) as SourceResumeForCounts;
    const items = parsed.experience?.items || [];
    const lines = items
      .map((item, index) => {
        const sourceIndex = typeof item.sourceIndex === "number" ? item.sourceIndex : index;
        const sourceCount = (item.blocks || []).filter((block) => block.type === "bullet" && block.text).length;
        const minCount = requiredMinBullets(sourceCount);
        if (!sourceCount || !minCount) return null;
        return `- sourceIndex ${sourceIndex}: исходно ${sourceCount} bullets → верни минимум ${minCount} adaptedBullets`;
      })
      .filter((line): line is string => Boolean(line));

    if (!lines.length) return "";

    return `
ОБЯЗАТЕЛЬНЫЙ ПЛАН ОБЪЁМА ПО КАЖДОМУ МЕСТУ РАБОТЫ:
${lines.join("\n")}

Если по sourceIndex вернёшь меньше указанного минимума adaptedBullets, ответ считается невалидным. Лучше сократить summary/skills, чем урезать опыт.
`.trim();
  } catch {
    return "";
  }
}

function isGenericForbiddenChange(value: string) {
  return (
    /личные\s+данные|контакты/iu.test(value) ||
    /не\s+повышать\s+уровень/iu.test(value) ||
    /не\s+добавлять\s+неподтвержд[её]нные.*метрик/iu.test(value) ||
    /компании,\s*должности,\s*даты,\s*проекты,\s*технологии\s+и\s+метрики/iu.test(value)
  );
}

function createAdaptationFitPrompt(fit: ResumeVacancyFitResult) {
  return JSON.stringify(
    {
      ...fit,
      forbiddenChanges: fit.forbiddenChanges.filter((item) => !isGenericForbiddenChange(item)),
      note:
        "Fit является подсказкой, а не запретом на усиление. Прямой источник истины — резюме кандидата. Generic-запрет на неподтверждённые метрики означает только запрет на фантастические KPI; аккуратные inferred-метрики по логической цепочке разрешены и нужны.",
    },
    null,
    2
  );
}

