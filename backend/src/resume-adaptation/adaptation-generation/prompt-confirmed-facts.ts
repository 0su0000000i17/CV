export function createConfirmedFactsBlock(confirmedFacts?: string[]) {
  if (!confirmedFacts?.length) return "";
  const lines = confirmedFacts.map((fact) => `- ${fact}`).join("\n");
  return `
ПОДТВЕРЖДЁННЫЕ КАНДИДАТОМ ФАКТЫ (прямые ответы кандидата на вопросы по пробелам между вакансией и
резюме, не выдумка сервиса). Каждый факт начинается с ПОМЕТКИ В КВАДРАТНЫХ СКОБКАХ — это решение
карьерного консультанта о том, КУДА факт встраивать, и оно ОБЯЗАТЕЛЬНО к исполнению:
${lines}

КАК ИСПОЛНЯТЬ ПОМЕТКИ (КРИТИЧЕСКИ ВАЖНО) — у каждого факта РОВНО ОДНО место назначения:
- [В ОПЫТ места «X»] → новый или переработанный пункт adaptedBullets ИМЕННО этого места работы
  (по sourceIndex из пометки): выполненное ДЕЙСТВИЕ в контексте задач этого места, семантически
  связанное с соседними bullets ("Настроил маршрутизацию через App Router при переносе разделов
  на Next.js 14"), а НЕ констатация навыка ("Использую App Router в проектах"). Помести новый
  пункт В МАССИВЕ adaptedBullets рядом с тематически связанными пунктами (порядок массива =
  порядок пунктов в резюме), а не приклеивай все новые пункты в конец списка. Такой факт
  ЗАПРЕЩЕНО дублировать в summary и additionalInfo. Название инструмента/технологии из факта
  дополнительно добавь в skills.
- МИМИКРИЯ ПОД ИСХОДНЫЙ ТЕКСТ (критично для пунктов из подтверждённых фактов): рекрутер не
  должен отличить пункт, добавленный из ответа кандидата, от исходных пунктов этого места.
  Ответ кандидата — СЫРЬЁ, а не готовый текст: разверни его до объёма, структуры и уровня
  детализации соседних пунктов, связав с проектом/системой/задачей, которая УЖЕ описана в этом
  месте. Если соседние пункты — развёрнутые формулировки "действие → способ → результат", то
  короткая констатация рядом с ними мгновенно выдаёт вставку.
  НЕПРАВИЛЬНО (соседние пункты подробно описывают систему мониторинга): "Использовал aiohttp
  для разработки API-сервисов."
  ПРАВИЛЬНО: "Разработал асинхронные API-сервисы на aiohttp для системы мониторинга
  законодательства, обеспечив параллельную обработку запросов к внешним источникам."
  Разворачивать можно ТОЛЬКО контекстом, который уже есть в этом месте резюме или в ответе
  кандидата: без новых цифр и не сильнее уровня владения, который подтвердил кандидат.
- [В НАВЫКИ ...] → пункт в skills формулировкой уровня, который подтвердил кандидат ("Docker
  (базовое понимание)" — так и пиши, не "Docker" без оговорки, если уровень базовый). Это
  закрывает требование вакансии — не выбрасывай подтверждённый факт, даже если уровень скромный.
  Уровень "базовое понимание / вне коммерческого опыта" НЕ пиши в bullets опыта — это не рабочий
  опыт. Если пометка разрешает фразу в «Обо мне» и ответ подтверждает применение в работе —
  добавь ОДНУ переформулированную фразу в summary по правилам блока SUMMARY, не копию ответа.
- [Одной строкой в «Обо мне» или дополнительную информацию] → ОДНА переформулированная фраза в
  summary ИЛИ один пункт в additionalInfo (сертификат, уровень языка, образование) — не в оба
  места сразу.
- [ОТКАЗ ...] → факт никуда не переносится, навык не добавляется и не упоминается.
- ЗАПРЕЩЕНО сваливать несколько разных ответов кандидата списком в additionalInfo или summary —
  каждый факт распределяется индивидуально по своей пометке, а не одним общим блоком.
- Не усиливай факт сильнее формулировки кандидата: "базовое понимание" остаётся базовым
  пониманием и не превращается в опыт использования.
- Если подтверждённый факт содержит числовой диапазон — перенеси диапазон целиком, обоими числами.

САМАЯ ЧАСТАЯ ОШИБКА (не повторяй её): свалить answer-часть подтверждённых фактов в additionalInfo
отдельными строками или склеить их в одно предложение-перечисление в конце summary — это выглядит
как приклеенный список ответов на вопросы, а не как резюме, и главная причина, по которой
адаптация получается недостаточно органичной.
ПРИМЕР НЕПРАВИЛЬНО (оба варианта — ошибка):
  "additionalInfo": ["Регулярно использую TGStat, LiveDune для аналитики", "Есть базовое понимание Bitrix24"]
  "summary": "...Регулярно использую CI/CD, Storybook, провожу unit/e2e тестирование, работаю по Scrum."
ПРИМЕР ПРАВИЛЬНО для тех же фактов:
  факт "Сбер — писал unit-тесты" → новый bullet в опыте Сбера ("Покрывала критичные компоненты
  unit-тестами..."); Scrum → в bullet/focus того места, где по контексту работала команда;
  TGStat/LiveDune → skills.secondary (+ bullet в опыте места, где велась аналитика, если ответ
  назвал место); "Bitrix24 (базовое понимание)" → только skills; additionalInfo не получает НИ
  ОДНОЙ из этих строк.
`.trim();
}
