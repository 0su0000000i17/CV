import type { NarrativeQualityIssue } from "./types.js";

export function createNarrativeQualityRetryNotice(issues: NarrativeQualityIssue[]) {
  const lines = issues.map((issue) =>
    `- [${issue.severity}] ${issue.location}: ${issue.reason}${issue.text ? ` — «${issue.text.slice(0, 220)}»` : ""}`
  );
  return `
ПРЕДЫДУЩИЙ РЕЗУЛЬТАТ НЕ ПРОШЁЛ РЕДАКТОРСКИЙ КОНТРОЛЬ ЦЕЛЬНОСТИ:
${lines.join("\n")}

Верни ПОЛНЫЙ JSON заново. Исправь blocking-нарушения и постарайся устранить advisory-замечания,
не ухудшая точность и содержательность сильных исходных формулировок. Сохрани структуру, компании,
даты и подтверждённые факты, но пересобери тексты как единое резюме карьерного консультанта:
- summary — 2-4 связанных предложения; первое может быть номинальным, остальные от первого
  лица без местоимения «я» ("разрабатываю", "выстраиваю", "специализируюсь");
- не используй третье лицо и причастия-самоописания;
- каждый блок опыта перепиши в едином стиле, а не оставляй старые пункты с дописанными строками;
- ответы кандидата встраивай внутрь тематически связанного bullet/предложения, не в конец блока.
`.trim();
}
