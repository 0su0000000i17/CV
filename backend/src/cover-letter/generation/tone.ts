import type { CoverLetterTone } from "../types.js";

export function describeTone(tone: CoverLetterTone) {
  if (tone === "strict_professional") return "Строгий профессиональный.";
  if (tone === "friendly_neutral") return "Дружелюбный нейтральный.";
  return "Уверенный короткий.";
}

export function describeToneStructure(tone: CoverLetterTone) {
  if (tone === "strict_professional") {
    return `
- 3 коротких абзаца после приветствия.
- Формальный деловой стиль без эмоций и разговорных оборотов.
- Не используй "я уверен", "буду рад", "спасибо за рассмотрение".
- Роль, релевантный опыт, конкретное совпадение с задачами, готовность обсудить.
- Финал спокойный: "Готов обсудить опыт и задачи роли."
`.trim();
  }
  if (tone === "friendly_neutral") {
    return `
- 3 коротких абзаца после приветствия.
- Живой, человеческий, но профессиональный тон.
- Можно показать интерес к задачам вакансии, если дальше сразу есть конкретика.
- Можно использовать "буду рад обсудить", но только один раз.
- Тон мягче строгого варианта, без фамильярности и шуток.
`.trim();
  }
  return `
- 1-2 коротких абзаца после приветствия.
- Максимум 650 символов без блока контактов.
- Без благодарностей, длинного вступления и "буду рад".
- Сразу к сути: роль, ключевое совпадение, готовность обсудить.
- Тон уверенный, без самоуверенности и фразы "я уверен".
`.trim();
}
