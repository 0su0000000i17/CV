export function createConfirmedFactsBlock(confirmedFacts?: string[]) {
  if (!confirmedFacts?.length) return "";
  const lines = confirmedFacts.map((fact) => `- ${fact}`).join("\n");
  return `
ПОДТВЕРЖДЁННЫЕ КАНДИДАТОМ ФАКТЫ (прямые ответы кандидата на уточняющие вопросы, не выдумка).
Каждый факт начинается с пометки маршрутизации в квадратных скобках. Исполни её буквально:
[ОТКАЗ] не переносится и не считается подтверждением; [В ОПЫТ] становится действием и
результатом в указанном вопросом месте; [В НАВЫКИ] не превращается в выдуманный проектный опыт;
[В SUMMARY] органично переписывается внутри общего рассказа, а не дописывается последней строкой.
${lines}

ПРАВИЛО АТОМАРНОСТИ ПОДТВЕРЖДЁННЫХ ФАКТОВ:
- metadata integration=atomic означает: факт должен стать отдельным законченным bullet. Разрешено
  заменить существующий bullet только когда вопрос, ответ и исходный bullet описывают ОДНО И ТО ЖЕ
  действие, а ответ лишь добавляет к нему метрику, масштаб, инструмент или результат.
- Нельзя присоединять новый факт к случайному существующему bullet ради сохранения количества строк.
  Совпадение компании недостаточно: должна совпадать рабочая ситуация и действие.
- Нельзя объединять в одном bullet разные действия, полученные из разных questionId. Несколько ответов
  одного questionId можно объединить, если они описывают части одного действия.
- После вставки перечитай каждый bullet отдельно: он должен выражать одну причинно связанную цепочку
  «задача -> действие -> результат», без смыслового скачка после запятой, союза или деепричастного оборота.

Используй эти факты, чтобы усилить соответствующие bullets, summary или skills — конкретизируй
именно то, что подтвердил кандидат, не сильнее его формулировки. РАСПРЕДЕЛЯЙ факты по резюме:
факт про конкретное место работы вставляй в bullets ИМЕННО этого места (лучше первым bullet),
формулируя как выполненное действие в контексте проекта, а не как констатацию навыка; факт про
инструмент/технологию — в опыт того места, где она логично применялась по стеку. ЗАПРЕЩЕНО
сваливать ответы кандидата списком в additionalInfo или summary — в additionalInfo идут только
факты, которые невозможно привязать ни к одному месту работы (сертификаты, язык, образование). Факт, не относящийся напрямую ни
к одному месту работы, отрази в summary или additionalInfo. Не используй факты, которых кандидат
не подтверждал. Если подтверждённый факт содержит числовой диапазон (например, "20-30%" или
"2-3 человека") — перенеси диапазон целиком, обоими числами, не обрывай на первом числе.

Факты про soft skills (взаимодействие, лидерство, самостоятельные решения, конфликт
приоритетов) никогда не оформляй прилагательными "коммуникабельный/стрессоустойчивый". Встрой их
в bullet соответствующего места по схеме ситуация или задача -> действие кандидата -> результат,
используя только подтверждённый контекст и не придумывая метрики.

Факты о постоянной практике/привычке (например, использование каких-либо инструментов) в bullets
и additionalInfo оформляй именной фразой без первого лица, как обычный пункт резюме:
ПРАВИЛЬНО (bullet): "Использование нейросетей (ChatGPT, Copilot, Cursor) для написания и проверки кода".
НЕПРАВИЛЬНО (bullet): "Регулярно использую нейросети для написания и проверки кода".
В summary, наоборот, тот же факт формулируй от первого лица настоящего времени, вплетая его в
общий рассказ ("...в работе применяю нейросети для ускорения написания и ревью кода").

КРИТЕРИЙ КАЧЕСТВА ВСТАВКИ: итоговое резюме должно читаться так, будто кандидат сам написал его
с нуля уже ЗНАЯ все эти факты — а не так, будто к готовому резюме приписали ответы из анкеты.
САМАЯ ЧАСТАЯ ОШИБКА (не повторяй её): свалить ответы кандидата отдельными строками в
additionalInfo или склеить их в одно предложение-перечисление в конце summary — это выглядит
как приклеенный список ответов на вопросы, а не как резюме.
ПРИМЕР НЕПРАВИЛЬНО (обе строки — ошибка):
  "additionalInfo": ["Прошёл курсы по оптимизации производительности", "Имею опыт интеграции с платёжными системами"]
  "summary": "...Прошёл курсы по оптимизации производительности веб-приложений. Имею опыт интеграции с платёжными системами."
ПРАВИЛЬНО: факт про интеграцию с платёжными системами уходит В BULLET того места работы, где она
происходила, в стиле остальных bullets этого места; факт про курс или дополнительное обучение,
если он усиливает позиционирование, органично вплетается в ОДНО из предложений summary, а не
становится отдельной последней строкой additionalInfo. Если факт нельзя встроить без ощущения
дописанного хвоста, не добавляй его в текст резюме и объясни это в warnings. После вставки перечитай каждое место работы целиком: новые bullets
не должны отличаться от старых ни ритмом, ни стилем, ни степенью конкретики.
`.trim();
}
